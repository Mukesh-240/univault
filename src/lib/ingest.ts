/**
 * INGEST — the single front door through which every document enters UNIVAULT.
 *
 * Plain-English picture:
 *   Whether a person uploads a file, or our synthetic-data generator loads demo documents,
 *   both go through THIS one function. That guarantees demo data is treated exactly like real
 *   data: no shortcuts, no special cases (rule 13 in the build prompts).
 *
 * What it does, step by step:
 *   1. Checks the incoming document is well-formed (right fields, sensible sizes). If not, it
 *      refuses and stores nothing.
 *   2. Computes a fingerprint (SHA-256 hash) of the document's content.
 *   3. Saves the document's permanent "cover record" (type, title, fingerprint) — this row can
 *      never be edited or deleted afterwards (the database enforces that).
 *   4. Saves the actual content (the "payload") in a separate table, so a user can later erase
 *      the sensitive content while the fingerprint and history remain.
 *   5. Writes an "uploaded" event (and "extracted" if OCR text came with it) to the history.
 *   6. Adds a line to the tamper-evident ledger.
 *
 * What it deliberately does NOT do:
 *   It never marks a document as "issuer-verified". A document only earns that badge later, when
 *   the verification step checks it against the (simulated) issuer's signed record.
 *
 * About the "synthetic" flag: it is stored only so the screen can say "this is demo data".
 * No decision anywhere in the app is allowed to look at it.
 */
import type { SupabaseClient } from "@supabase/supabase-js";
import { z } from "zod"; // Zod = a small library that checks data has the expected shape
import { canon, sha256 } from "./crypto";
import { append } from "./ledger";
import { log } from "./scrub";

// The database connection; we need from() for tables and rpc() for the ledger check.
export type Db = Pick<SupabaseClient, "from" | "rpc">;

/**
 * "Where did this demo document come from?" — attached to every synthetic document so the UI can
 * show e.g. "Synthetic: generated by recipe graduate_demo, seed 7".
 */
const SyntheticOrigin = z.object({
  generator: z.string().min(1),                          // name of the program that made it
  version: z.string().min(1),                            // version of that program
  seed: z.number().int(),                                // the random seed (same seed = same data)
  recipe: z.string().min(1),                             // which scenario recipe produced it
  dataset: z.enum(["dev", "heldout", "showcase", "scans"]), // which generated set it belongs to ("scans" = the OCR test images)
  ref: z.string().optional(),                            // its reference inside that set
});
export type SyntheticOrigin = z.infer<typeof SyntheticOrigin>;

// Safety limits so a huge or junk upload is rejected instead of clogging the database.
const MAX_FIELDS = 40;
const MAX_TEXT = 20_000;
// Field names must look like "date_of_birth": lower-case letters, digits and underscores.
const fieldKey = z.string().regex(/^[a-z][a-z0-9_]{0,40}$/, "field names must be lower_snake_case");

/**
 * The shape every incoming document must have. Anything that doesn't match is rejected with a
 * plain reason (this is also how the "malformed upload" fault is handled).
 */
export const DocumentInput = z.object({
  owner: z.string().min(1).max(80).default("demo"),         // whose vault it goes into
  doc_type: z.string().regex(/^[a-z][a-z0-9_]{1,40}$/),     // e.g. "degree_certificate"
  title: z.string().min(1).max(200),                        // human-readable title
  issuer: z.string().max(200).nullable(),                   // who issued it (may be unknown)
  serial: z.string().max(80).nullable(),                    // issuer's serial number (may be absent)
  capture: z.enum(["digital", "scan"]),                     // original digital file, or a scanned paper
  fields: z.record(fieldKey, z.string().max(500))           // the document's data, e.g. { name: "...", cgpa: "8.4" }
    .refine((f) => Object.keys(f).length <= MAX_FIELDS, "too many fields"),
  body_text: z.string().max(MAX_TEXT).optional(),           // free text (e.g. a letter's body)
  hidden_text: z.string().max(MAX_TEXT).optional(),         // text present in the file but invisible on the page
  ocr_confidence: z.record(fieldKey, z.number().min(0).max(1)).nullable().optional(), // for scans: how sure the text reader was, per field (0–1)
  language_scripts: z.array(z.enum(["latin", "telugu"])).default([]), // which writing systems appear
  synthetic: z.boolean(),                                   // label only: is this demo data?
  synthetic_origin: SyntheticOrigin.nullable().optional(),  // label only: where the demo data came from
});
export type DocumentInput = z.input<typeof DocumentInput>;

/**
 * The part of a document that is "content" (and therefore erasable later).
 * Its fingerprint becomes the document's permanent identity ("content address").
 */
export function payloadOf(d: z.output<typeof DocumentInput>) {
  return { capture: d.capture, fields: d.fields, body_text: d.body_text ?? null, hidden_text: d.hidden_text ?? null };
}

/** Fingerprint of the content. `canon` sorts the keys first so identical content always gives the identical fingerprint. */
export const documentHash = (d: z.output<typeof DocumentInput>): string => sha256(canon(payloadOf(d)));

/** What the caller gets back: the new document's id and its fingerprint. */
export interface IngestResult { id: string; sha256: string }

/**
 * Store one document. Throws (and stores nothing) if the input is malformed;
 * throws with the database's reason if a save is refused.
 */
export async function ingestDocument(db: Db, raw: unknown): Promise<IngestResult> {
  // Step 1: check the shape. parse() throws a readable error if anything is wrong.
  const d = DocumentInput.parse(raw);

  // Step 2: fingerprint the content.
  const hash = documentHash(d);

  // Step 3: the permanent cover record. Note source_tier is ALWAYS "user_uploaded" here;
  // only verification can later show it as issuer-verified.
  const doc = await db.from("documents").insert({
    owner: d.owner, doc_type: d.doc_type, title: d.title, issuer: d.issuer, serial: d.serial, sha256: hash,
    source_tier: "user_uploaded", language_scripts: d.language_scripts, synthetic: d.synthetic,
    synthetic_origin: d.synthetic_origin ?? null,
  }).select("id").single();
  if (doc.error) {
    // Log only the error code — never the document's contents.
    log("error", "ingest: document insert failed", { code: doc.error.code });
    throw new Error(`document insert failed: ${doc.error.message}`);
  }
  const id = (doc.data as { id: string }).id;

  // Step 4: the erasable content, stored separately.
  // ponytail: no cross-table transaction with the anon key; if this fails, an immutable cover record
  // remains without content, and the vault should show it as "upload incomplete". Upgrade path: a
  // single database function that does steps 3–5 in one transaction.
  const pay = await db.from("document_payloads").insert({ document_id: id, content: payloadOf(d), ocr_confidence: d.ocr_confidence ?? null });
  if (pay.error) {
    log("error", "ingest: payload insert failed", { id, code: pay.error.code });
    throw new Error(`payload insert failed: ${pay.error.message}`);
  }

  // Step 5: history events. "extracted" means text was read from a scan; it is marked
  // confirmed: false because OCR text is never trusted until the person confirms it.
  const events: { document_id: string; state: string; detail: Record<string, unknown> }[] = [
    { document_id: id, state: "uploaded", detail: { capture: d.capture } },
  ];
  if (d.ocr_confidence) events.push({ document_id: id, state: "extracted", detail: { source: "ocr", confirmed: false } });
  const ev = await db.from("document_events").insert(events);
  if (ev.error) {
    log("error", "ingest: event insert failed", { id, code: ev.error.code });
    throw new Error(`event insert failed: ${ev.error.message}`);
  }

  // Step 6: one ledger line (ids and fingerprint only — no personal data).
  await append(db, "document.uploaded", { document_id: id, sha256: hash, doc_type: d.doc_type, capture: d.capture });
  log("info", "ingest: stored", { id, doc_type: d.doc_type });
  return { id, sha256: hash };
}
