/**
 * DATA CARD — writes docs/DATA_CARD.md, the one-page description of our synthetic test data.
 * Run: npm run data-card   (after: npm run synth:all)
 *
 * It is generated (not hand-written) from the showcase labels and the dev/held-out labels, so it
 * always matches the data actually produced. Evaluation tooling may read labels; the app never does.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Labels } from "../synthetic/generate";

const root = process.cwd();
const labels = (set: string): Labels | null => {
  const f = join(root, "synthetic", "out", "labels", `labels-${set}.json`);
  return existsSync(f) ? (JSON.parse(readFileSync(f, "utf8")) as Labels) : null;
};

const show = labels("showcase");
if (!show?.conflicts) throw new Error("Run `npm run synth:all` first (showcase labels missing).");
const sets = ["dev", "heldout"].map(labels).filter((l): l is Labels => l !== null);

/** Short reference: "showcase:showcase.graduate_demo.0:marksheet" -> "marksheet". */
const short = (ref: string) => ref.split(":").pop();
/** Compact one-line rendering of an expected answer. */
const brief = (o: Record<string, unknown>) => Object.entries(o).map(([k, v]) => `${k}=${typeof v === "object" ? JSON.stringify(v) : v}`).join("; ");

const lines: string[] = [
  "# UNIVAULT — Data card (synthetic data)",
  "",
  `_Generated by \`npm run data-card\` from the generator's labels. Generator ${show.meta.generator} v${show.meta.version}; reference date ${show.meta.reference_date}._`,
  "",
  "**Everything here is synthetic.** People are random combinations from a generic name bank; ID numbers start with `0000`; all institutions are named \"Synthetic …\", \"Example …\" or \"Sample …\". The issuer is a simulation signed with our own demo keys. No real person, document or government service is involved.",
  "",
  "**How expected answers are set:** by construction — the generator knows what it planted and writes it to a separate labels file. The app never reads labels; only tests and the evaluation harness do.",
  "",
  `## Showcase persona (recipe \`graduate_demo\`, seed ${show.meta.seed}) — ${show.conflicts.length} planted conflicts`,
  "",
  "| # | Planted problem | Expected detector | Documents | Expected result |",
  "|---|---|---|---|---|",
  ...show.conflicts.map((c) => `| ${c.id} | ${c.title} | \`${c.detector}\` | ${c.refs.map(short).join(", ")} | ${brief(c.expected)} |`),
  "",
  "### Negative controls (must raise no alarm)",
  "",
  ...(show.negatives ?? []).map((n) => `- **${short(n.ref)}** — ${n.why}`),
  "",
  "## Range-testing sets",
  "",
  "| Set | Seed | Documents | Cases | Levels | Min cases / level | Negative or benign cases |",
  "|---|---|---|---|---|---|---|",
  ...sets.map((l) => {
    const per = new Map<string, number>();
    for (const c of l.cases) per.set(`${c.dimension}/${c.level}`, (per.get(`${c.dimension}/${c.level}`) ?? 0) + 1);
    const neg = l.cases.filter((c) => c.expected.alarms === 0 || c.expected.same_person === false || c.expected.flagged === false).length;
    return `| ${l.meta.set} | ${l.meta.seed} | ${l.meta.documents} | ${l.cases.length} | ${per.size} | ${Math.min(...per.values())} | ${neg} |`;
  }),
  "",
  "Dimensions: names, dates, tampering, OCR, issuer state, duplicates, injection, over-broad requests, sharing, negative controls (full per-level counts in `synthetic/out/coverage-<set>.md`). Tuning uses **dev** only; headline metrics are reported on **held-out**.",
  "",
  "## Conventions and known limits",
  "",
  "- Dates are relative to the reference date (\"expired 9 days ago\" = 9 days before it). Regenerate on demo day.",
  "- A 29 February birthday is reached on 1 March in non-leap years (used by the leap-day age cases).",
  "- OCR damage is simulated in the dataset (misread characters + per-field confidence, sometimes wrongly confident on purpose, for calibration). Real OCR runs separately on the generated scan images in `public/scans/`.",
  "- Telugu name forms come from a small generic name bank; matching quality on other names is not claimed.",
  "",
];
writeFileSync(join(root, "docs", "DATA_CARD.md"), lines.join("\n"));
console.info(`docs/DATA_CARD.md written (${show.conflicts.length} conflicts, ${show.negatives?.length ?? 0} negative controls, ${sets.length} range sets)`);
